"""Shared report metadata. Every document shows units, engine/catalogue/rule versions, generated time,
validation status and - when provisional/demo - the PROVISIONAL banner."""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import List, Optional, Tuple

from ..config import APP_VERSION

BANNER = "PROVISIONAL — DEMO RULES/DATA — NOT FOR PRODUCTION"
INVALID_BANNER = "INVALID — FAILED INDEPENDENT VALIDATION — DO NOT RELEASE"
WATERMARK = "DEMO — NOT FOR PRODUCTION"


@dataclass
class ReportMeta:
    title: str
    reference: str                       # e.g. "Cutting job #12"
    validation_status: str
    units: str = "mm"
    engine_version: str = "-"
    catalogue_version: str = "-"
    rule_set: str = "-"
    validator: str = "-"
    provisional: bool = False
    project: Optional[str] = None
    generated_by: Optional[str] = None
    generated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"))
    extra: List[Tuple[str, str]] = field(default_factory=list)

    @property
    def invalid(self) -> bool:
        return self.validation_status == "INVALID"

    @property
    def banners(self) -> List[str]:
        b = []
        if self.invalid:
            b.append(INVALID_BANNER)
        if self.provisional:
            b.append(BANNER)
        return b

    def rows(self) -> List[Tuple[str, str]]:
        r = [("Document", self.title), ("Reference", self.reference)]
        if self.project:
            r.append(("Project", self.project))
        r += [("Units", self.units + " (lengths), m² (areas), degrees (angles)"),
              ("Validation status", self.validation_status),
              ("Validator", self.validator),
              ("Engine version", self.engine_version),
              ("Catalogue version", self.catalogue_version),
              ("Rule set", self.rule_set),
              ("Provisional / demo", "YES — " + BANNER if self.provisional else "no"),
              ("Generated at", self.generated_at),
              ("Generated by", self.generated_by or "-"),
              ("Application", f"ITMC FenestrationOS {APP_VERSION}")]
        return r + list(self.extra)


def fmt(v, nd: int = 1) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        s = f"{v:,.{nd}f}"
        return s
    return str(v)
